// =====================================================================
// 0-1 背包问题（背包 DP 系列之一）
//
// 【问题】有 n 件物品，第 i 件的重量为 w[i]、价值为 v[i]，每件最多
//        拿 1 次。背包总容积为 V，问能带走的最大总价值是多少。
// 【状态】dp[j] 表示“容积恰好为 j 时能装下的最大价值”
// 【转移】dp[j] = max(dp[j], dp[j - w[i]] + v[i])
// 【重点】一维数组的容积 j 必须【从大到小】枚举。因为正序枚举时，
//        dp[j-w[i]] 可能已被本轮更新过，等价于同一件物品被重复取用，
//        那便退化成了完全背包 —— 这正是 01 背包与完全背包的本质区别。
// 【复杂度】时间 O(n*V)，空间可压到 O(V)
//
//  ---- 输入样例 ----
//  4 5
//  1 2
//  2 4
//  3 4
//  4 5
//  ---- 输出 ----
//  2D answer: 8     （选 2 号(2,4) 和 3 号(3,4)，总重 5、总价值 8）
//  1D answer: 8
// =====================================================================
#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n, V;
    cin >> n >> V;
    vector<int> w(n + 1), v(n + 1);
    for (int i = 1; i <= n; ++i) cin >> w[i] >> v[i];

    // ---------- 写法 1：二维 dp（直观，便于理解状态转移） ----------
    // dp[i][j]：只考虑前 i 件物品、容积恰好为 j 时的最大价值
    vector<vector<int>> dp2(n + 1, vector<int>(V + 1, 0));
    for (int i = 1; i <= n; ++i) {
        for (int j = 0; j <= V; ++j) {
            dp2[i][j] = dp2[i - 1][j];                 // 情况一：不拿第 i 件
            if (j >= w[i])                             // 情况二：拿第 i 件
                dp2[i][j] = max(dp2[i][j], dp2[i - 1][j - w[i]] + v[i]);
        }
    }

    // ---------- 写法 2：一维滚动数组（竞赛中最常用、省空间） ----------
    vector<int> dp1(V + 1, 0);
    for (int i = 1; i <= n; ++i)
        for (int j = V; j >= w[i]; --j)   // ★ 倒序：保证每件物品最多被用一次
            dp1[j] = max(dp1[j], dp1[j - w[i]] + v[i]);

    cout << "2D answer: " << dp2[n][V] << '\n';
    cout << "1D answer: " << dp1[V] << "\n\n";

    cout << "final 1D dp[0..V]:\n";
    for (int j = 0; j <= V; ++j) cout << dp1[j] << ' ';
    cout << '\n';
    return 0;
}
